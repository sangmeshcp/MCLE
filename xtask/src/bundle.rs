use crate::manifest::{clouds, load_all, root};
use anyhow::{bail, Result};
use std::fmt::Write as _;

fn files() -> Result<Vec<(std::path::PathBuf, String)>> {
    let services = load_all()?;
    let clouds = clouds()?;
    let mut cargo = String::new();
    writeln!(cargo, "# @generated by `cargo xtask bundle`. DO NOT EDIT.")?;
    writeln!(cargo, "[package]\nname = \"mcle-bundle\"\ndescription = \"Generated registry of enabled MCLE plugins (cargo features).\"")?;
    writeln!(cargo, "version.workspace = true\nedition.workspace = true\nlicense.workspace = true\npublish.workspace = true\n")?;
    writeln!(
        cargo,
        "[dependencies]\nmcle-gateway.workspace = true\nmcle-sdk.workspace = true"
    )?;
    for c in &clouds {
        writeln!(
            cargo,
            "mcle-cloud-{c} = {{ workspace = true, optional = true }}"
        )?;
    }
    for s in &services {
        let rel = s
            .dir
            .strip_prefix(root())
            .unwrap_or(&s.dir)
            .display()
            .to_string();
        writeln!(
            cargo,
            "{} = {{ path = \"../../{rel}\", optional = true }}",
            s.crate_name()
        )?;
    }
    writeln!(cargo, "\n[features]")?;
    let mut all: Vec<String> = Vec::new();
    for c in &clouds {
        writeln!(cargo, "cloud-{c} = [\"dep:mcle-cloud-{c}\"]")?;
    }
    for s in &services {
        writeln!(
            cargo,
            "{} = [\"cloud-{}\", \"dep:{}\"]",
            s.feature(),
            s.toml.service.cloud,
            s.crate_name()
        )?;
        all.push(format!("\"{}\"", s.feature()));
    }
    for c in &clouds {
        let mut members = vec![format!("\"cloud-{c}\"")];
        members.extend(
            services
                .iter()
                .filter(|s| &s.toml.service.cloud == c)
                .map(|s| format!("\"{}\"", s.feature())),
        );
        writeln!(cargo, "all-{c} = [{}]", members.join(", "))?;
    }
    let all_clouds: Vec<String> = clouds.iter().map(|c| format!("\"all-{c}\"")).collect();
    writeln!(cargo, "all = [{}]", all_clouds.join(", "))?;
    writeln!(cargo, "default = [\"all\"]\n\n[lints]\nworkspace = true")?;

    let mut reg = String::new();
    writeln!(reg, "// @generated by `cargo xtask bundle`. DO NOT EDIT.")?;
    writeln!(
        reg,
        "#![allow(unused_mut, unused_variables, unused_imports, clippy::all)]"
    )?;
    writeln!(reg, "use mcle_gateway::Plugins;\nuse mcle_sdk::Host;\n")?;
    writeln!(reg, "pub const KNOWN_SERVICES: &[(&str, &str, &str)] = &[")?;
    for s in &services {
        writeln!(
            reg,
            "    ({:?}, {:?}, {:?}),",
            s.toml.service.cloud,
            s.toml.service.name,
            s.feature()
        )?;
    }
    writeln!(reg, "];\n")?;
    writeln!(
        reg,
        "// `clouds`: cloud names to enable; empty enables every compiled-in cloud."
    )?;
    writeln!(
        reg,
        "pub fn plugins(host: &Host, clouds: &[String]) -> Plugins {{"
    )?;
    writeln!(reg, "    let mut p = Plugins::default();")?;
    writeln!(
        reg,
        "    let on = |c: &str| clouds.is_empty() || clouds.iter().any(|x| x == c);"
    )?;
    for c in &clouds {
        let cc = c.replace('-', "_");
        writeln!(
            reg,
            "    #[cfg(feature = \"cloud-{c}\")]\n    if on({c:?}) {{"
        )?;
        writeln!(reg, "        let adapter = mcle_cloud_{cc}::adapter(host);")?;
        for s in services.iter().filter(|s| &s.toml.service.cloud == c) {
            writeln!(
                reg,
                "        #[cfg(feature = \"{}\")]\n        p.services.push({}::facade(host, &*adapter));",
                s.feature(),
                s.crate_name().replace('-', "_")
            )?;
        }
        writeln!(reg, "        p.adapters.push(adapter);\n    }}")?;
    }
    writeln!(reg, "    p\n}}")?;

    let lib = "// @generated by `cargo xtask bundle`. DO NOT EDIT.\n#![forbid(unsafe_code)]\n\nmod registry;\npub use registry::*;\n".to_string();
    let base = root().join("crates").join("mcle-bundle");
    Ok(vec![
        (base.join("Cargo.toml"), cargo),
        (
            base.join("src").join("registry.rs"),
            crate::gen::rustfmt(&reg),
        ),
        (base.join("src").join("lib.rs"), lib),
    ])
}

pub fn run(check: bool) -> Result<()> {
    let mut stale = Vec::new();
    for (path, text) in files()? {
        if std::fs::read_to_string(&path).unwrap_or_default() != text {
            if check {
                stale.push(path.display().to_string());
            } else {
                if let Some(p) = path.parent() {
                    std::fs::create_dir_all(p)?;
                }
                std::fs::write(&path, text)?;
                println!(
                    "bundle: wrote {}",
                    path.strip_prefix(root()).unwrap_or(&path).display()
                );
            }
        }
    }
    if !stale.is_empty() {
        bail!(
            "mcle-bundle is stale (run `cargo xtask bundle`):\n  {}",
            stale.join("\n  ")
        );
    }
    Ok(())
}
