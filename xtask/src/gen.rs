pub fn const_name(op: &str) -> String {
    let s = crate::ir::snake(op).to_ascii_uppercase();
    let s: String = s
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    let s = s
        .split('_')
        .filter(|p| !p.is_empty())
        .collect::<Vec<_>>()
        .join("_");
    if s.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        format!("OP_{s}")
    } else {
        s
    }
}

pub fn cloud_expr(cloud: &str) -> String {
    match cloud {
        "aws" => "CloudId::AWS".into(),
        "azure" => "CloudId::AZURE".into(),
        "gcp" => "CloudId::GCP".into(),
        "oci" => "CloudId::OCI".into(),
        "ibm" => "CloudId::IBM".into(),
        other => format!("CloudId::ext({other:?})"),
    }
}

fn cap(s: &str) -> String {
    let mut c = s.chars();
    c.next()
        .map(|f| f.to_uppercase().chain(c).collect())
        .unwrap_or_default()
}

pub fn render(entry: &ServiceEntry, r: &Resolved) -> Result<String> {
    let t = &entry.toml;
    let s = &t.service;
    let mut o = String::new();
    writeln!(
        o,
        "// @generated by `cargo xtask codegen` from {} ({}). DO NOT EDIT.",
        std::iter::once(&s.api.spec)
            .chain(s.api.extra_specs.iter())
            .cloned()
            .collect::<Vec<_>>()
            .join(", "),
        s.api.format
    )?;
    writeln!(o, "#![allow(missing_docs, dead_code, clippy::all)]")?;
    writeln!(o, "use mcle_sdk::*;\n")?;
    let engines: Vec<String> = s.engines.iter().map(|e| format!("{e:?}")).collect();
    writeln!(
        o,
        "pub static MANIFEST: ServiceManifest = ServiceManifest {{ cloud: {}, name: {:?}, display: {:?}, tier: Tier::{}, engines: &[{}], protocol: {:?}, signing_name: {:?} }};\n",
        cloud_expr(&s.cloud), s.name, s.display, s.tier, engines.join(", "), r.protocol, r.signing_name
    )?;
    writeln!(o, "pub mod op {{\n    use mcle_sdk::OpId;")?;
    for (i, op) in r.ops.iter().enumerate() {
        writeln!(
            o,
            "    pub const {}: OpId = OpId({i});",
            const_name(&op.name)
        )?;
    }
    writeln!(o, "}}\n")?;
    writeln!(o, "pub static OPS: [OpMeta; {}] = [", r.ops.len())?;
    for op in &r.ops {
        let lro = match op.lro.as_str() {
            "create" => "Create",
            "update" => "Update",
            "delete" => "Delete",
            "action" => "Action",
            _ => "None",
        };
        let idem = match op.idempotency.split_once(':') {
            Some(("token", f)) => format!("Idempotency::Token({f:?})"),
            _ if op.idempotency == "natural" => "Idempotency::Natural".into(),
            _ => "Idempotency::None".into(),
        };
        let emits: Vec<String> = op
            .emits
            .iter()
            .map(|e| format!("EventKind({e:?})"))
            .collect();
        let crud = match &op.crud {
            Some((ty, v)) => format!(
                "Some(CrudBinding {{ resource: {ty:?}, verb: CrudVerb::{} }})",
                v.rust()
            ),
            None => "None".into(),
        };
        writeln!(
            o,
            "    OpMeta {{ name: {:?}, iam_action: IamAction({:?}), resource: {}, level: FidelityLevel::{}, lro: LroBehavior::{lro}, emits: &[{}], idempotency: {idem}, plane: Plane::{}, crud: {crud} }},",
            op.name, op.iam_action, op.resource, op.level, emits.join(", "), cap(&op.plane)
        )?;
    }
    writeln!(o, "];\n")?;
    writeln!(
        o,
        "pub static ROUTES: RouteTable = RouteTable {{ case_insensitive: {}, routes: &[",
        s.case_insensitive_paths
    )?;
    for (i, op) in r.ops.iter().enumerate() {
        let m = match &op.matcher {
            Matcher::Rest {
                method,
                path,
                query,
            } => {
                let q: Vec<String> = query.iter().map(|k| format!("{k:?}")).collect();
                format!(
                    "RouteMatch::Rest {{ method: {method:?}, path: {path:?}, query: &[{}] }}",
                    q.join(", ")
                )
            }
            Matcher::Target(t) => format!("RouteMatch::Target({t:?})"),
            Matcher::QueryAction(a) => format!("RouteMatch::QueryAction({a:?})"),
        };
        writeln!(o, "    Route {{ op: OpId({i}), matcher: {m} }},")?;
    }
    writeln!(o, "] }};\n")?;
    writeln!(
        o,
        "pub static CRUD_RESOURCES: [CrudResource; {}] = [",
        t.crud.resources.len()
    )?;
    for (ty, hints) in &t.crud.resources {
        let h: Vec<String> = hints
            .iter()
            .map(|(k, v)| format!("({k:?}, {v:?})"))
            .collect();
        writeln!(
            o,
            "    CrudResource {{ type_name: {ty:?}, hints: &[{}] }},",
            h.join(", ")
        )?;
    }
    writeln!(o, "];")?;
    Ok(rustfmt(&o))
}

pub fn rustfmt(src: &str) -> String {
    let child = Command::new("rustfmt")
        .args(["--edition", "2021", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn();
    let Ok(mut child) = child else {
        return src.to_string();
    };
    if let Some(mut stdin) = child.stdin.take() {
        let _ = stdin.write_all(src.as_bytes());
    }
    match child.wait_with_output() {
        Ok(out) if out.status.success() && !out.stdout.is_empty() => {
            String::from_utf8_lossy(&out.stdout).into_owned()
        }
        _ => src.to_string(),
    }
}

pub fn run(check: bool) -> Result<()> {
    let mut stale = Vec::new();
    for e in crate::manifest::load_all()? {
        let r = resolve(&e)?;
        let text = render(&e, &r)?;
        let path = e.dir.join("gen").join("mod.rs");
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        if current != text {
            if check {
                stale.push(
                    path.strip_prefix(root())
                        .unwrap_or(&path)
                        .display()
                        .to_string(),
                );
            } else {
                std::fs::create_dir_all(path.parent().unwrap_or(&e.dir))?;
                std::fs::write(&path, text)?;
                println!(
                    "codegen: wrote {}",
                    path.strip_prefix(root()).unwrap_or(&path).display()
                );
            }
        }
    }
    if !stale.is_empty() {
        bail!(
            "generated code is stale (run `cargo xtask codegen`):\n  {}",
            stale.join("\n  ")
        );
    }
    Ok(())
}
